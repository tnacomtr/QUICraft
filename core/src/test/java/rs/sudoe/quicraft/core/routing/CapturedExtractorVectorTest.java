package rs.sudoe.quicraft.core.routing;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.Test;
import rs.sudoe.quicraft.core.routing.extract.ExtractorRegistry;
import static org.junit.jupiter.api.Assertions.*;

/**
 * 13.7's review evidence for the production extractor identifiers: real uncompressed frames,
 * captured on the live 26.1.2 client between decompression and the game's packet decoder, paired
 * with the position or list the game itself reported for the same packet and the live packet name
 * and id. The file is generated by {@code ExtractorVectorGameTest}
 * ({@code -Pquicraft.emitExtractorVectors=<file>}, see docs/platforms/fabric.md); this test keeps
 * the checked-in copy honest.
 *
 * <p>Each frame must decode, under its recorded production identifier, to the recorded
 * expectation; cutting the frame below the length its layout needs must reject it, and every longer
 * prefix must still decode to the same expectation, because bytes after the layout belong to the
 * rest of the real packet (13.7). Every row of the reviewed mapping must have a sample, and every
 * position layout must have seen both a negative and a nonnegative coordinate (the capture's near
 * phase exists for the latter).
 */
class CapturedExtractorVectorTest {
    private static final String FILE = "captured-775-vectors.txt";

    /** 13.7's reviewed mapping: layout id to the real 775 packets it serves. */
    private static final Map<String, Set<String>> REVIEWED = reviewed();

    private static Map<String, Set<String>> reviewed() {
        Map<String, Set<String>> reviewed = new LinkedHashMap<String, Set<String>>();
        reviewed.put("mc775.chunk_xz.v1", setOf("minecraft:level_chunk_with_light"));
        reviewed.put("mc775.block_position.v1",
                setOf("minecraft:block_update", "minecraft:block_entity_data"));
        reviewed.put("mc775.section_position.v1", setOf("minecraft:section_blocks_update"));
        reviewed.put("mc775.chunk_list.v1", setOf("minecraft:chunks_biomes"));
        reviewed.put("mc775.join.v1", setOf("minecraft:chunk_batch_finished", "minecraft:block_changed_ack"));
        return reviewed;
    }

    @Test void everyCapturedFrameDecodesToThePositionTheGameReported() throws Exception {
        int lines = 0;
        boolean trailingBytesSeen = false;
        for (String line : lines()) {
            if (line.startsWith("#")) continue;
            String[] fields = line.split("\\|", -1);
            assertEquals(5, fields.length, line);
            String identifier = fields[0];
            byte[] frame = hex(fields[1]);
            String expectation = fields[2];
            String packetName = fields[3];
            int packetId = Integer.parseInt(fields[4]);
            lines++;
            assertTrue(ExtractorRegistry.isProduction(identifier), identifier);
            assertEquals(packetId, varInt(frame), line);
            assertNotNull(REVIEWED.get(identifier), "not a reviewed layout: " + identifier);
            assertTrue(REVIEWED.get(identifier).contains(packetName),
                    identifier + " does not serve " + packetName);
            ExtractorRegistry.Decoder decoder = ExtractorRegistry.productionDecoder(identifier);
            assertEquals(expectation, result(decoder.decode(frame)), line);
            assertTrue(expectation.equals("JOIN") || !expectation.isEmpty(),
                    "a position layout needs a non-empty expectation: " + line);
            // The layout is a prefix of a real packet: shorter than it needs rejects, every longer
            // prefix, ending at the whole packet, decodes to the same result. A packet whose layout
            // runs to its last byte (a chunk list) has no trailing bytes, but the others do.
            int consumed = shortestPrefix(decoder, frame, expectation);
            assertTrue(consumed <= frame.length, line);
            trailingBytesSeen |= consumed < frame.length;
            for (int i : new int[] {consumed, consumed + 1, consumed + 2, frame.length}) {
                if (i <= frame.length) {
                    assertEquals(expectation, result(decoder.decode(Arrays.copyOf(frame, i))),
                            line + " prefix " + i);
                }
            }
            for (int i : new int[] {0, consumed - 1, consumed - 2}) {
                if (i >= 0) {
                    byte[] cut = Arrays.copyOf(frame, i);
                    assertThrows(IllegalArgumentException.class, () -> decoder.decode(cut), line + " cut to " + i);
                }
            }
        }
        assertTrue(lines >= REVIEWED.size(), "a capture with fewer samples than layouts is not evidence: " + lines);
        assertTrue(trailingBytesSeen, "no captured frame carries bytes past its layout");
    }

    @Test void theCaptureCoversEveryReviewedPacketAndBothCoordinateSigns() throws Exception {
        Set<String> covered = new LinkedHashSet<String>();
        Set<String> negative = new LinkedHashSet<String>();
        Set<String> nonnegative = new LinkedHashSet<String>();
        for (String line : lines()) {
            if (line.startsWith("#")) continue;
            String[] fields = line.split("\\|", -1);
            covered.add(fields[0] + " " + fields[3]);
            boolean any = false;
            boolean anyNegative = false;
            for (String pair : fields[2].split(";")) {
                if (pair.isEmpty() || pair.equals("JOIN")) continue;
                for (String value : pair.split(",")) {
                    any = true;
                    if (Long.parseLong(value) < 0) anyNegative = true;
                }
            }
            if (anyNegative) negative.add(fields[0]);
            if (any && !anyNegative) nonnegative.add(fields[0]);
        }
        for (Map.Entry<String, Set<String>> entry : REVIEWED.entrySet()) {
            for (String packet : entry.getValue()) {
                assertTrue(covered.contains(entry.getKey() + " " + packet),
                        "no captured sample for " + entry.getKey() + " " + packet);
            }
            if (!entry.getKey().equals("mc775.join.v1")) {
                assertTrue(negative.contains(entry.getKey()),
                        "no negative-coordinate sample for " + entry.getKey());
                assertTrue(nonnegative.contains(entry.getKey()),
                        "no nonnegative-coordinate sample for " + entry.getKey());
            }
        }
    }

    /** The shortest prefix of {@code frame} that decodes to {@code expectation}; it must exist. */
    private static int shortestPrefix(ExtractorRegistry.Decoder decoder, byte[] frame, String expectation) {
        int low = 1;
        int high = frame.length;
        while (low < high) {
            int middle = (low + high) / 2;
            if (decodes(decoder, Arrays.copyOf(frame, middle), expectation)) high = middle;
            else low = middle + 1;
        }
        return low;
    }

    private static boolean decodes(ExtractorRegistry.Decoder decoder, byte[] packet, String expectation) {
        try {
            return result(decoder.decode(packet)).equals(expectation);
        } catch (IllegalArgumentException e) {
            return false;
        }
    }

    /** The decoded result in the capture file's notation. */
    private static String result(ExtractorRegistry.Result result) {
        if (result.kind == ExtractorRegistry.Kind.JOIN) return "JOIN";
        StringBuilder out = new StringBuilder();
        for (Extractor.Position p : result.positions) {
            if (out.length() != 0) out.append(';');
            out.append(p.chunkX).append(',').append(p.chunkZ);
        }
        return out.toString();
    }

    private static List<String> lines() throws Exception {
        InputStream in = CapturedExtractorVectorTest.class.getResourceAsStream(FILE);
        assertNotNull(in, FILE + " is missing: regenerate it with ExtractorVectorGameTest");
        List<String> lines = new ArrayList<String>();
        try (BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            for (String line; (line = reader.readLine()) != null; ) if (!line.isEmpty()) lines.add(line);
        }
        return lines;
    }

    private static int varInt(byte[] frame) {
        int value = 0;
        for (int i = 0; i < 5; i++) {
            int b = frame[i] & 255;
            value |= (b & 127) << (7 * i);
            if ((b & 128) == 0) return value;
        }
        throw new IllegalStateException("no packet id");
    }

    private static Set<String> setOf(String... values) {
        return new LinkedHashSet<String>(Arrays.asList(values));
    }

    private static byte[] hex(String value) {
        byte[] bytes = new byte[value.length() / 2];
        for (int i = 0; i < bytes.length; i++) bytes[i] = (byte) Integer.parseInt(value.substring(i * 2, i * 2 + 2), 16);
        return bytes;
    }
}
